"""Fire-safety pillar scores from verified evidence and measured results. No SI.

For each investigation and each of NASA's three pillars (prevention, detection, suppression):
  * evidence   a sentence from the record that the Pillar pointer chose and the rules checked (app/nimbus/pillars.py),
               or one the team confirmed by hand in data/pillar_evidence.yaml. Its quote is shown with the score.
  * data link  measured results that bear on the pillar, read from the harmonised tests and table families
               (rules: `pillar_data_links` in data/vocabulary.yaml).
Points: a Research Impacts sentence 3, Objective or Hypothesis 2, Approach 1, plus 2 for a data link; 5 points is a full score.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

PILLARS = ("prevention", "detection", "suppression")
POINTS = {"impacts": 3, "objective": 2, "hypothesis": 2, "approach": 1}
LINK_POINTS = 2
FULL_POINTS = 5
FIELD_LABEL = {"impacts": "Research Impacts", "objective": "Objective", "hypothesis": "Hypothesis", "approach": "Approach"}


def _flat(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip().lower()


def load_evidence(data_dir: Path) -> tuple[dict, dict]:
    """(SI-pointed evidence generated by app/nimbus/pillars.py, the team's hand-confirmed entries). Either may be empty."""
    generated = data_dir / "pillar_evidence.json"
    confirmed = data_dir / "pillar_evidence.yaml"
    found = json.loads(generated.read_text(encoding="utf-8")).get("pillars", {}) if generated.exists() else {}
    team = (yaml.safe_load(confirmed.read_text(encoding="utf-8")) or {}) if confirmed.exists() else {}
    return found, team


def data_links(inv: dict, tests: list[dict], rules: list[dict]) -> dict[str, dict]:
    """Measured results that bear on each pillar, as {pillar: {"why", "tests" or "rows", "file"}}."""
    out: dict[str, dict] = {}
    for rule in rules:
        pillar = rule["pillar"]
        if pillar in out:
            continue
        if "outcome_kind" in rule:
            hits = [t for t in tests if t.get("outcome_kind") == rule["outcome_kind"]
                    and (t["values"].get("outcome") or {}).get("value") == rule["outcome"]]
            if hits:
                out[pillar] = {"why": f"{len(hits)} {rule['text']}", "tests": len(hits), "file": hits[0]["file"]}
        elif "family" in rule:
            for table in inv.get("tables", []):
                if table.get("family") == rule["family"] and table.get("tier") in rule["tiers"]:
                    out[pillar] = {"why": f"{inv['table_rows']} rows: {rule['text']}", "rows": inv["table_rows"], "file": table["file"]}
                    break
    return out


def assemble(inv: dict, entry: dict | None, team: dict | None, links: dict[str, dict]) -> dict[str, dict]:
    """The pillar record the app shows: {pillar: {status, score, points, field, quote, provenance, data_link}}."""
    result = {}
    for pillar in PILLARS:
        item = (entry or {}).get(pillar) or {"status": "not assessed"}
        provenance = "SI pointed at the sentence; rules checked it"
        if team and pillar in team:                                   # the team's hand-confirmed sentence wins
            item = {"status": "evidence", "field": team[pillar]["field"], "quote": team[pillar]["quote"]}
            provenance = "team-confirmed"
        status, field, quote = item["status"], item.get("field"), item.get("quote")
        if not inv["is_combustion"]:
            result[pillar] = {"status": "not applicable", "score": None, "points": 0, "field": None, "quote": None, "provenance": None, "data_link": None}
            continue
        if status == "evidence" and _flat(quote) not in _flat(inv.get(field) or ""):
            status, field, quote = "stale", None, None                # the record changed since the quote was chosen
        link = links.get(pillar)
        if status == "evidence":
            shown = "evidence"
        elif status == "stale":
            shown = "stale"
        elif link:
            shown = "data only"
        else:
            shown = "not assessed" if status == "not assessed" else "none"
        points = (POINTS.get(field, 0) if shown == "evidence" else 0) + (LINK_POINTS if link else 0)
        result[pillar] = {"status": shown, "score": None if shown == "not assessed" else round(min(1.0, points / FULL_POINTS), 3), "points": points,
                          "field": field, "quote": quote, "provenance": provenance if shown == "evidence" else None, "data_link": link}
    return result


def describe(pillar: dict) -> str:
    """One plain sentence about a pillar record, for tooltips and the chat's evidence."""
    status, link = pillar["status"], pillar.get("data_link")
    measured = f" Measured results: {link['why']}." if link else ""
    if status == "evidence":
        return f"{FIELD_LABEL[pillar['field']]}: “{pillar['quote'][:220]}”{measured}"
    if status == "data only":
        return f"No sentence in the record states it.{measured}"
    return {"not applicable": "Not applicable: not combustion research.", "not assessed": "Not assessed yet.",
            "stale": "The quoted sentence is no longer in the record; data refresh needed."}.get(
        status, "No sentence in the record shows the research informs this pillar.")
